import assert from 'node:assert/strict';
import {buildKigakuPageData as build} from '../src/kigaku-page-data.js';
const input={methodKey:'nine-star-ki',referenceInstant:'2026-11-08T00:00:00+09:00',birthClock:{date:'1990-06-15',time:'12:34',countryCode:'JP',zoneId:'Asia/Tokyo',zoneConfirmed:true,offsetChoiceMinutes:null}};
const result=build(input);
assert.equal(result.pages.length,14);
assert.equal(result.pages.filter(p=>p.state==='unconnected').length,6);
assert(result.pages.every(p=>p.publicationAllowed===false));
assert.equal(result.verificationState,'review-required');
assert.deepEqual(build(JSON.parse(JSON.stringify(input))), result);
assert(build({...input,methodKey:'numerology'}).pages.every(p=>p.state==='unconnected'&&p.data===null));
assert(build({...input,referenceInstant:'bad'}).pages.filter(p=>p.state==='calculation-error').length===8);
const missing=build({...input,birthClock:null});
assert.equal(missing.pages[0].state,'required-missing');
assert.equal(missing.pages[4].state,'available');
const boundary=build({...input,birthClock:{...input.birthClock,date:'2026-02-04',time:null}});
assert.equal(boundary.pages[0].data,null);
assert.equal(boundary.pages[0].state,'required-missing');
assert.equal(build({...input,referenceInstant:'2100-06-01T00:00:00+09:00'}).pages[13].state,'required-missing');
assert.deepEqual(input.birthClock.date,'1990-06-15');
console.log('F4 Kigaku: eight calculation mappings, six unconnected, missing/boundary/isolation/JSON round trip verified; formal publication disabled.');
