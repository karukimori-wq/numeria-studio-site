import assert from "node:assert/strict";
import { calculateNumerology } from "../src/numerology-calculator.js";
import { normalizeNumerologyNameInputs, updateNumerologyNameInputs } from "../src/numerology-name-input.js";
import { withNumerologyCalculationCheckpoint } from "../src/numerology-result-checkpoint.js";
import { validateConfirmedDivinationResult } from "../src/divination-result-contract.js";

const snapshot = { id: "checkpoint-session", divination: "numerology", name: "架空", birthName: "TARO YAMADA", birthday: "2009-11-11", visitDate: "2026-10-19" };
let names = updateNumerologyNameInputs(normalizeNumerologyNameInputs(null), { role: "subject", operation: "edit", romanName: "TARO YAMADA" }, snapshot).value;
snapshot.numerologyNameInputs = updateNumerologyNameInputs(names, { role: "subject", operation: "confirm" }, snapshot).value;
const original = JSON.stringify(snapshot), saved = withNumerologyCalculationCheckpoint(snapshot), checkpoint = saved.numerologyCalculation;
assert.equal(JSON.stringify(snapshot), original);
assert.equal(checkpoint.status, "calculated");
assert.equal(checkpoint.source.referenceDate, "2026-10-19");
assert.equal(checkpoint.source.nameSources.subject.romanName, "TAROYAMADA");
assert.equal(checkpoint.source.nameSources.subject.nameKind, "birth");
assert.equal(checkpoint.results[0].data.lifePath, 33);
assert.equal(checkpoint.pageResults.length, 14);
assert.equal(checkpoint.verificationState, "review-required");
assert.equal(validateConfirmedDivinationResult(checkpoint).ok, false);
assert.equal("validationEvidence" in checkpoint, false);
assert.equal("pageAvailability" in checkpoint, false);
assert.deepEqual(withNumerologyCalculationCheckpoint(saved), saved, "Repeated snapshot capture must be deterministic for save ACK comparison");
assert.deepEqual(withNumerologyCalculationCheckpoint(JSON.parse(JSON.stringify(saved))), saved);
const changed = withNumerologyCalculationCheckpoint({ ...saved, visitDate: "2027-01-01" });
assert.equal(changed.numerologyCalculation.results[0].data.personalYear, 6);
assert.equal(saved.numerologyCalculation.results[0].data.personalYear, 5, "Captured snapshot stays immutable during later edits");
const missing = withNumerologyCalculationCheckpoint({ ...snapshot, numerologyNameInputs: null }).numerologyCalculation;
assert.equal(missing.results[0].data.destiny, null);
assert.equal(missing.results[0].data.lifePath, 33);
assert.equal(missing.pageResults.find(row => row.pageDefinitionId === "NUM-01").status, "input-incomplete");
assert.equal(withNumerologyCalculationCheckpoint({ ...saved, divination: "tarot" }).numerologyCalculation, undefined);
assert.equal(withNumerologyCalculationCheckpoint(null), null);
const noReference = withNumerologyCalculationCheckpoint({ ...snapshot, visitDate: "" }).numerologyCalculation;
assert.equal(noReference.status, "input-incomplete");
assert.ok(Object.values(noReference.results[0].data).every(value => value === null));
const pins = calculateNumerology({ birthday: "2009-11-11", referenceDate: "2026-10-19" }).pinnacles;
assert.deepEqual(pins.slice(1).map(row => row.startDate), ["2039-11-11", "2048-11-11", "2057-11-11"]);
assert.equal(pins[0].endDateExclusive, pins[1].startDate);
const leap = calculateNumerology({ birthday: "2000-02-29", referenceDate: "2026-10-19" }).pinnacles;
assert.ok(leap.every(row => row.dateBoundaryStatus === "resolved"));
assert.equal(leap[1].startDate, "2030-03-01");
assert.equal(leap[0].endDateExclusive, "2030-03-01");
assert.equal(leap[3].startDate, "2048-02-29");
const endOfRange = calculateNumerology({ birthday: "9990-01-01", referenceDate: "9999-01-01" }).pinnacles;
assert.ok(endOfRange.some(row => row.dateBoundaryStatus === "unresolved"));
console.log("Numerology checkpoints: deterministic capture, input provenance, missing values, isolated publication, date boundaries and unresolved anniversaries verified.");
