import assert from "node:assert/strict";
import { REPORT_PAGE_DEFINITIONS } from "../src/report-page-definitions.js";
import { REPORT_RESULT_REFERENCES, reportResultReferenceFor } from "../src/report-result-references.js";
import { calculateNumerology } from "../src/numerology-calculator.js";
assert.equal(REPORT_RESULT_REFERENCES.length, 85);
assert.deepEqual(REPORT_RESULT_REFERENCES.map(row => row.pageDefinitionId).sort(), REPORT_PAGE_DEFINITIONS.map(row => row.pageDefinitionId).sort());
assert.ok(REPORT_RESULT_REFERENCES.every(row => row.resultReference && row.publicationRule && row.connectionStatus === "unconnected"));
assert.deepEqual(reportResultReferenceFor("NUM-13").figureTypes, ["FIG-TIME", "FIG-TABLE"]);
assert.deepEqual(reportResultReferenceFor("TAR-02").figureTypes, ["FIG-CARDS"]);
assert.equal(reportResultReferenceFor("unknown"), null);
const input = { birthday: "2009-11-11", romanName: "TARO YAMADA", referenceDate: "2026-11-01" };
const full = calculateNumerology(input);
assert.equal(full.status, "calculated");
assert.deepEqual(full.coreNumbers, { lifePath: 33, birthdayNumber: 11, attitude: 4, destiny: 9, soul: 1, personality: 8, maturity: 6, personalYear: 5 });
assert.equal(full.personalMonth, 7);
assert.deepEqual(full.personalYears.map(item => item.year), [2022, 2023, 2024, 2025, 2026, 2027, 2028, 2029, 2030]);
assert.equal(full.personalYears.filter(item => item.current).length, 1);
assert.equal(full.personalYears[4].value, 5);
assert.deepEqual(full.nameDigitCounts, { 1: 4, 2: 1, 3: 0, 4: 2, 5: 0, 6: 1, 7: 1, 8: 0, 9: 1 });
assert.deepEqual(full.missingDigits, [3, 5, 8]);
assert.deepEqual(full.mostFrequentDigits, [1]);
assert.deepEqual(calculateNumerology({ ...input, romanName: "Ｔａｒｏ Ｙａｍａｄａ" }).coreNumbers, full.coreNumbers);
const missingName = calculateNumerology({ ...input, romanName: "" });
assert.equal(missingName.coreNumbers.lifePath, 33);
assert.deepEqual(missingName.missingCoreNumbers, ["destiny", "soul", "personality", "maturity"]);
assert.equal(missingName.missingDigits, null);
assert.equal(calculateNumerology({ ...input, romanName: "RY" }).coreNumbers.soul, null);
assert.equal(calculateNumerology({ ...input, romanName: "RY" }).coreNumbers.personality, 7);
assert.equal(calculateNumerology({ ...input, romanName: "AI" }).coreNumbers.personality, null);
assert.equal(calculateNumerology({ ...input, romanName: "AI" }).coreNumbers.soul, 1);
assert.equal(calculateNumerology({ ...input, referenceDate: "2027-01-01" }).coreNumbers.personalYear, 6);
assert.equal(calculateNumerology({ ...input, referenceDate: "2026-01-01" }).coreNumbers.personalYear, 5);
for (const birthday of ["2025-02-29", "1900-02-29", "2020-04-31", "2027-01-01", "bad"]) assert.equal(calculateNumerology({ ...input, birthday }).status, "input-incomplete");
assert.equal(calculateNumerology({ ...input, birthday: "2000-02-29" }).status, "calculated");
assert.equal(calculateNumerology({ ...input, birthday: "0001-01-01", referenceDate: "0001-01-01" }).personalYears, null);
assert.equal(calculateNumerology({ ...input, romanName: "太郎" }).status, "input-incomplete");
assert.equal(calculateNumerology({ ...input, romanName: 123 }).status, "input-incomplete");
assert.equal("validationEvidence" in full, false, "calculation must not fabricate independent validation");
assert.equal("pageAvailability" in full, false, "calculation must not automatically authorize formal publication");
console.log("F4: all 85 reference rows and numerology core/date/name/cycle rules verified; formal connections remain unconnected.");
